const interpolate = (template, params = {}) => String(template).replace(
  /\{\{\s*(\w+)\s*\}\}/g,
  (match, name) => (params[name] == null ? match : String(params[name]))
);

const resolveLocale = (language) => {
  const normalized = normalizeInterfaceLanguageCode(language);
  return CONTENT_STRINGS[normalized] ? normalized : 'en';
};

export const hasContentString = (key) => Object.prototype.hasOwnProperty.call(CONTENT_STRINGS.en, key);

// translateContent('ja', 'error.explain_daily_limit', { limit: 250 })
export const translateContent = (language, key, params = {}) => {
  const table = CONTENT_STRINGS[resolveLocale(language)];
  const template = table[key] ?? CONTENT_STRINGS.en[key] ?? key;
  return interpolate(template, params);
};

const PARAMS_REQUIRED = {
  explain_daily_limit: ['limit'],
  assess_daily_limit: ['limit'],
  text_too_long: ['limit'],
  too_many_items: ['limit'],
  entry_too_short_words: ['length', 'min'],
  entry_too_short_characters: ['length', 'min'],
  entry_too_long_words: ['length', 'max'],
  entry_too_long_characters: ['length', 'max'],
};

const STATUS_FALLBACK_CODES = {
  401: 'auth_failed',
  403: 'forbidden',
  404: 'not_found',
  413: 'invalid_request',
  429: 'daily_quota_exceeded',
  500: 'service_unavailable',
  502: 'service_unavailable',
  503: 'service_unavailable',
  504: 'timeout',
};

// The content-strings key for an API error code, or null when the code is
// unknown or its message needs numbers the error didn't carry.
export const errorKeyForCode = (code, params = {}) => {
  const normalized = typeof code === 'string' ? code.trim() : '';
  if (!normalized) return null;
  const key = normalized === 'request_too_large' ? 'error.invalid_request' : `error.${normalized}`;
  if (!hasContentString(key)) return null;
  const required = PARAMS_REQUIRED[normalized] ?? [];
  if (required.some((name) => params?.[name] == null)) {
    return normalized.startsWith('entry_too_') || normalized === 'text_too_long' || normalized === 'too_many_items'
      ? 'error.invalid_request'
      : null;
  }
  return key;
};

// User-facing text, in the interface language, for a failed backend request
// (an axios error, or anything shaped like { code, params, status }). Uses the
// backend's stable `code` when present, else the HTTP status, else network /
// timeout detection. Never returns the backend's English `detail`.
export const localizeApiError = (error, language) => {
  const data = error?.response?.data;
  const code = data?.code ?? error?.code_api ?? error?.apiCode;
  const params = data?.params ?? error?.apiParams ?? {};
  const key = errorKeyForCode(code, params);
  if (key) {
    return translateContent(language, key, params);
  }
  const status = error?.response?.status ?? error?.status;
  if (status === 422 || status === 400) {
    return translateContent(language, 'error.invalid_request');
  }
  if (STATUS_FALLBACK_CODES[status]) {
    return translateContent(language, `error.${STATUS_FALLBACK_CODES[status]}`);
  }
  if (error?.code === 'ECONNABORTED' || error?.code === 'ETIMEDOUT' || /timed? ?out/i.test(String(error?.message ?? ''))) {
    return translateContent(language, 'error.timeout');
  }
  if (error?.isAxiosError && !error?.response) {
    return translateContent(language, 'error.network');
  }
  return translateContent(language, 'error.unknown');
};

// Proficiency levels. Korean "Noeul Reading Levels" have translated names;
// HSK and CEFR level names are international and stay as they are.
const KO_LEVEL_ALIASES = {
  'lower elementary': 1,
  'upper elementary': 2,
  'lower intermediate': 3,
  'upper intermediate': 4,
  'lower advanced': 5,
  'upper advanced': 6,
};

// `levelOrRank` is a stored level name ("Lower Elementary", "HSK 3") or a
// rank; `fallbackLabel` is shown when there is nothing to translate.
export const localizedLevelLabel = (targetLanguage, levelOrRank, language, fallbackLabel = null) => {
  const target = String(targetLanguage || '').toLowerCase().split('-')[0];
  if (levelOrRank == null || levelOrRank === '') return fallbackLabel ?? '';
  const raw = String(levelOrRank).trim();
  if (target !== 'ko') return fallbackLabel ?? raw;
  const rank = Number.isFinite(Number(raw)) ? Number(raw) : KO_LEVEL_ALIASES[raw.toLowerCase()];
  return rank >= 1 && rank <= 6 ? translateContent(language, `level.ko.${rank}`) : (fallbackLabel ?? raw);
};

export const localizedLevelDescription = (targetLanguage, rank, fallback, language) => {
  const target = String(targetLanguage || '').toLowerCase().split('-')[0];
  const key = `level.${target}.${rank}.description`;
  return hasContentString(key) ? translateContent(language, key) : (fallback ?? '');
};

export const localizedLevelSystem = (system, language) => (
  system === 'Noeul Reading Levels' ? translateContent(language, 'level.system.noeul') : (system ?? '')
);

// Chinese character formation type (zh_characters.db etymology_type).
export const localizedEtymologyType = (type, language) => {
  const key = `chinese.etymology.${String(type || '').trim().toLowerCase()}`;
  return hasContentString(key) ? translateContent(language, key) : (type ?? '');
};

// The label shown next to content that is in English because no translation
// was available. `reason` is 'offline' (request failed with no response) or
// anything else (translation not available).
export const englishFallbackLabel = (language, reason) => translateContent(
  language,
  reason === 'offline' ? 'content.englishFallbackOffline' : 'content.englishFallback'
);
