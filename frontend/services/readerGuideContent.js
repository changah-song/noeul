export const GUIDE_PAGE_LANGUAGES = Object.keys(PAGES);

/**
 * The sample page for a learning language, with its help in the interface
 * language. Chinese follows the reader's script setting.
 */
export const getGuidePage = (targetLanguage, interfaceLanguage, chineseScript) => {
    const target = normalizeLanguageCode(targetLanguage);
    const base = PAGES[target] ?? PAGES.ko;
    const page = target === 'zh' && normalizeChineseScript(chineseScript) === 'zh-Hant' && base.traditional
        ? { ...base, ...base.traditional }
        : base;
    const ui = normalizeInterfaceLanguageCode(interfaceLanguage);
    const fallback = target === 'en' ? 'ko' : 'en';
    return {
        ...page,
        target,
        gloss: page.glosses[ui] ?? page.glosses[fallback],
    };
};
